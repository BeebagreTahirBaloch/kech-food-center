import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import sharp from 'sharp';
import { menuSections, getSizes } from '../src/data/menu.js';
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
grant usage on schema auth to anon,authenticated,service_role; grant execute on function auth.uid() to anon,authenticated,service_role;
create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
alter table storage.objects enable row level security; grant usage on schema storage to anon,authenticated; grant select,insert,update,delete on storage.objects to anon,authenticated;`);
await db.exec(await readFile(new URL('../supabase/migrations/202610300001_backend_menu.sql',import.meta.url),'utf8'));
const owner='11111111-1111-4111-8111-111111111111', stranger='22222222-2222-4222-8222-222222222222';
await db.query('insert into auth.users values ($1),($2)',[owner,stranger]);
await db.query('insert into admins values($1)',[owner]);
const category=(await db.query("insert into categories(name) values('Pizza') returning id")).rows[0].id;
async function role(name,user='') { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[user]); await db.exec(`set role ${name}`); }
async function save(item,sizes) { return (await db.query('select public.save_menu_item($1,$2) id',[JSON.stringify(item),JSON.stringify(sizes)])).rows[0].id; }
async function price(lines) { return (await db.query('select public.price_menu_cart($1) items',[JSON.stringify(lines)])).rows[0].items; }
await role('anon');
await assert.rejects(db.query("insert into categories(name) values('Unauthorized')"));
await assert.rejects(db.query('select * from admins'));
await assert.rejects(price([]));
await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('menu-images','bad.webp')"));
await role('authenticated',stranger);
assert.equal((await db.query('select * from admins')).rows.length,0);
await assert.rejects(save({category_id:category,name:'Bad',base_price:1},[]),/Not authorized/);
await assert.rejects(db.query('insert into admins values($1)',[stranger]));
await role('authenticated',owner);
const item=await save({category_id:category,name:'Pizza',base_price:null},[{label:'Small',price:500,sort_order:0},{label:'Large',price:800,sort_order:1}]);
let sizes=(await db.query('select * from item_sizes where item_id=$1 order by sort_order',[item])).rows;
await assert.rejects(db.query('delete from categories where id=$1',[category]),/foreign key/);
await db.query("insert into storage.objects(bucket_id,name) values('menu-images','allowed.webp')");
await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('other','bad.webp')"));
const second=await save({category_id:category,name:'Drink',base_price:100},[]);
await role('service_role');
const cart=[{itemId:item,sizeId:sizes[0].id,quantity:2,price:1}];
const snapshot=await price(cart);
assert.equal(snapshot[0].lineTotal,1000); assert.equal(snapshot[0].optionLabel,'Small');
await assert.rejects(price([{...cart[0],itemId:second}]),/does not have sizes/);
await assert.rejects(price([{...cart[0],quantity:1.5}]),/Invalid quantity/);
await assert.rejects(price([{...cart[0],sizeId:null}]),/available size/);
await role('authenticated',owner);
await save({id:item,category_id:category,name:'New pizza',base_price:null},sizes.map((s,i)=>({...s,price:600+i*200,sort_order:1-i})));
await role('service_role');
assert.equal((await price(cart))[0].unitPrice,600);
assert.equal(snapshot[0].unitPrice,500); assert.equal(snapshot[0].name,'Pizza');
await db.query('update menu_items set is_available=false where id=$1',[item]);
await assert.rejects(price(cart),/unavailable/);
await db.query('update menu_items set is_available=true,is_deleted=true where id=$1',[item]);
await assert.rejects(price(cart),/unavailable/);
await role('anon');
assert.equal((await db.query('select * from menu_items where id=$1',[item])).rows.length,0);
await role('authenticated',owner);
await assert.rejects(save({category_id:category,name:'Zero',base_price:0},[]));
await assert.rejects(save({category_id:category,name:'Missing',base_price:null},[]));
assert.equal((await db.query("select * from menu_items where name in ('Zero','Missing')")).rows.length,0);
await save({id:item,category_id:category,name:'New pizza',base_price:null},[sizes[1]]);
await role('service_role');
await db.query('update menu_items set is_deleted=false where id=$1',[item]);
await assert.rejects(price(cart),/available size/);
await db.close();
let count=0;
for(const category of menuSections) for(const item of category.items) {
 const options=getSizes(item); assert.ok(options.length || item.price>0);
 const image=new URL('../public/'+item.image.replace(/^\.\//,''),import.meta.url);
 const buffer=await sharp(await readFile(image)).rotate().resize({width:1000,height:1000,fit:'inside',withoutEnlargement:true}).webp({quality:85}).toBuffer();
 assert.ok(buffer.length<=2097152,`${item.name} image exceeds upload limit`); count++;
}
console.log(`PASS: menu migration, role policies, storage policies, atomic saves, pricing, size validation, snapshot preservation, and ${count} seed images.`);
